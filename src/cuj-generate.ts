import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { GuardrailsConfig } from './config.js';
import { resolveJourney } from './cuj-tokens.js';

type Journey = GuardrailsConfig['journeys']['items'][string];
const header = '// Generated by guardrails journeys generate-tests; ';
const hash = (text: string) => createHash('sha256').update(text).digest('hex');
/** Sort object keys recursively; array order is semantic. */
export function canonical(value: unknown): string {
  const sort = (v: unknown): unknown => Array.isArray(v) ? v.map(sort) : v && typeof v === 'object'
    ? Object.fromEntries(Object.entries(v).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([k, x]) => [k, sort(x)])) : v;
  return JSON.stringify(sort(value));
}
export function journeyData(cwd: string, cfg: GuardrailsConfig): Record<string, unknown> {
  const file = join(cwd, cfg.journeys.dataFile);
  if (!existsSync(file)) return {};
  const data: unknown = JSON.parse(readFileSync(file, 'utf8'));
  if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error('journeys.dataFile must contain a JSON object');
  return data as Record<string, unknown>;
}
export function generatedSpec(id: string, input: Journey, data: Record<string, unknown>): string {
  if (!/^[A-Za-z0-9_-]+$/.test(id)) throw new Error(`Unsafe journey filename: ${id}`);
  const resolved = resolveJourney(input, data);
  const journey = { id, title: resolved.title, run: resolved.run ?? [] };
  return `${header}journey-hash: ${hash(canonical(journey))}\nimport { test } from '@playwright/test';\nimport { runJourney } from './_runtime';\n\ntest(${JSON.stringify(`${id} ${journey.title}`)}, async ({ page }) => {\n  await runJourney(page, ${JSON.stringify(journey, null, 2)});\n});\n`;
}
export function generatedRuntime(): string {
  const runtime = readFileSync(new URL('../template/site/cuj-runtime.ts', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
  return `${header}runtime-hash: ${hash(runtime)}\n${runtime}`;
}
export function generateTests(cwd: string, cfg: GuardrailsConfig, out = 'e2e/cuj', check = false): string[] {
  const data = journeyData(cwd, cfg);
  const files = new Map<string, string>([['_runtime.ts', generatedRuntime()]]);
  const errors: string[] = [];
  for (const [id, journey] of Object.entries(cfg.journeys.items).sort(([a], [b]) => a.localeCompare(b))) {
    if (!journey.run?.length) continue;
    try { files.set(`${id}.spec.ts`, generatedSpec(id, journey, data)); }
    catch (error) { errors.push(`${id}: ${error instanceof Error ? error.message : String(error)}`); }
  }
  const changed: string[] = [];
  for (const [name, content] of files) {
    const file = join(cwd, out, name);
    const before = existsSync(file) ? readFileSync(file, 'utf8') : undefined;
    if (before !== undefined && !before.split('\n')[0].startsWith(header)) errors.push(`Refusing to overwrite unmanaged file: ${file}`);
    if (before !== content) changed.push(name);
  }
  if (errors.length) throw new Error(errors.join('\n'));
  if (check && changed.length) throw new Error(`Generated CUJ files differ: ${changed.join(', ')}; regenerate with guardrails journeys generate-tests`);
  if (!check) for (const name of changed) {
    const file = join(cwd, out, name);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, files.get(name)!);
  }
  return changed;
}
