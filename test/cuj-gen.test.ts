import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
import { expect, it } from 'vitest';
import { generateTests, generatedSpec, canonical } from '../src/cuj-generate.js';
import { e2eTests } from '../src/checks/journeys.js';
import { repo } from './helpers/repo.js';
import { fakePage } from './helpers/cuj-page.js';
import type { PageLike } from '../src/cuj-runtime.js';

const item = { title: 'Visitor calls {{client.phone}}', priority: 'P0', steps: ['Open contact'], run: [{ goto: '/contact' }, { expectHref: { selector: 'a', value: 'tel:{{client.phone}}' } }] };
const config = { version: 1, journeys: { items: { 'CUJ-CONTACT': item } } };
it('CUJ-06 generates stable resolved hashes and literal titles indexed by JRN-1', () => {
  const r = repo({ '.guardrails/client-data.json': JSON.stringify({ client: { phone: '555' } }) }, config);
  expect(generateTests(r.dir, r.ctx().config)).toEqual(['_runtime.ts', 'CUJ-CONTACT.spec.ts']);
  const text = readFileSync(join(r.dir, 'e2e/cuj/CUJ-CONTACT.spec.ts'), 'utf8');
  const resolved = { id: 'CUJ-CONTACT', title: 'Visitor calls 555', run: [{ goto: '/contact' }, { expectHref: { selector: 'a', value: 'tel:555' } }] };
  const hash = createHash('sha256').update(canonical(resolved)).digest('hex');
  expect(text.split('\n')[0]).toBe('// Generated by guardrails journeys generate-tests; journey-hash: ' + hash);
  expect(text).toContain('test("CUJ-CONTACT Visitor calls 555", async ({ page }) => {');
  expect(text).not.toContain('@ws42/guardrails');
  expect(text.endsWith('\n')).toBe(true);
  expect(text).not.toContain('\r');
  expect(e2eTests(r.ctx().config, r.dir, ['e2e/cuj/CUJ-CONTACT.spec.ts']).get('CUJ-CONTACT')).toEqual([{ file: 'e2e/cuj/CUJ-CONTACT.spec.ts', line: 5 }]);
  expect(generateTests(r.dir, r.ctx().config)).toEqual([]);
  expect(generateTests(r.dir, r.ctx().config, undefined, true)).toEqual([]);
  const runtime = readFileSync(join(r.dir, 'e2e/cuj/_runtime.ts'), 'utf8');
  const body = runtime.slice(runtime.indexOf('\n') + 1);
  expect(runtime.split('\n')[0]).toBe('// Generated by guardrails journeys generate-tests; runtime-hash: ' + createHash('sha256').update(body).digest('hex'));
});
it('CUJ-06 refuses unmanaged files atomically and check never writes missing or edited files', () => {
  const r = repo({ 'e2e/cuj/_runtime.ts': 'user code' }, { version: 1, journeys: { items: { 'CUJ-CONTACT': { ...item, title: 'Visitor calls business', run: [{ goto: '/' }] } } } });
  expect(() => generateTests(r.dir, r.ctx().config)).toThrow('unmanaged');
  expect(readFileSync(join(r.dir, 'e2e/cuj/_runtime.ts'), 'utf8')).toBe('user code');
  r.remove('e2e/cuj/_runtime.ts');
  expect(() => generateTests(r.dir, r.ctx().config, undefined, true)).toThrow('differ');
  expect(() => readFileSync(join(r.dir, 'e2e/cuj/_runtime.ts'))).toThrow();
  generateTests(r.dir, r.ctx().config);
  const file = 'e2e/cuj/CUJ-CONTACT.spec.ts';
  const changed = readFileSync(join(r.dir, file), 'utf8') + '// edit\n'; r.write({ [file]: changed });
  expect(() => generateTests(r.dir, r.ctx().config, undefined, true)).toThrow('differ');
  expect(readFileSync(join(r.dir, file), 'utf8')).toBe(changed);
});
it('CUJ-06 aggregates unresolved tokens and honours custom data and output files', () => {
  const r = repo({}, config);
  expect(() => generateTests(r.dir, r.ctx().config)).toThrow('CUJ-CONTACT: Unresolved or empty tokens: client.phone');
  r.write({ 'data.json': '{"client":{"phone":"123"}}' });
  const cfg = r.ctx().config; cfg.journeys.dataFile = 'data.json';
  expect(generateTests(r.dir, cfg, 'custom')).toEqual(['_runtime.ts', 'CUJ-CONTACT.spec.ts']);
  expect(readFileSync(join(r.dir, 'custom/CUJ-CONTACT.spec.ts'), 'utf8')).toContain('tel:123');
  expect(canonical({ z: 1, a: { z: 2, a: 3 } })).toBe('{"a":{"a":3,"z":2},"z":1}');
});
it('CUJ-06 loads generated modules with a Playwright module stub and executes their exact calls', async () => {
  const r = repo({ '.guardrails/client-data.json': '{"client":{"phone":"555"}}' }, config);
  generateTests(r.dir, r.ctx().config);
  const f = fakePage();
  const registered: { title: string; body: (args: { page: PageLike }) => Promise<void> }[] = [];
  const load = (file: string, require: (id: string) => unknown) => {
    const exports = {};
    const javascript = ts.transpileModule(readFileSync(join(r.dir, 'e2e/cuj', file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
    runInNewContext(javascript, { exports, require, URL, setTimeout, clearTimeout });
    return exports;
  };
  const runtime = load('_runtime.ts', () => { throw new Error('unexpected runtime import'); });
  load('CUJ-CONTACT.spec.ts', (id) => {
    if (id === './_runtime') return runtime;
    if (id === '@playwright/test') return { test: (title: string, body: (args: { page: PageLike }) => Promise<void>) => registered.push({ title, body }) };
    throw new Error('unexpected import ' + id);
  });
  expect(registered.map((test) => test.title)).toEqual(['CUJ-CONTACT Visitor calls 555']);
  await registered[0].body({ page: f.page });
  expect(f.calls).toEqual([['route', '**/*'], ['goto', '/contact', { timeout: 10000 }], ['locator', 'a'], ['first'], ['getAttribute', 'href', { timeout: 10000 }]]);
  expect(generatedSpec('CUJ-CONTACT', r.ctx().config.journeys.items['CUJ-CONTACT'], { client: { phone: '555' } })).toBe(readFileSync(join(r.dir, 'e2e/cuj/CUJ-CONTACT.spec.ts'), 'utf8'));
});

it('CUJ-06 CLI generates, checks and rejects stale output without writing it', () => {
  const r = repo({ '.guardrails/client-data.json': '{"client":{"phone":"555"}}' }, config);
  const cli = fileURLToPath(new URL('../dist/cli.js', import.meta.url));
  const invoke = (...args: string[]) => spawnSync(process.execPath, [cli, 'journeys', ...args, '--cwd', r.dir], { encoding: 'utf8' });
  expect(invoke('scaffold').status).toBe(0);
  expect(invoke('generate-tests').status).toBe(0);
  expect(invoke('generate-tests', '--check').status).toBe(0);
  r.write({ '.guardrails/client-data.json': '{"client":{"phone":"changed"}}' });
  expect(invoke('generate-tests', '--check').status).toBe(1);
  expect(readFileSync(join(r.dir, 'e2e/cuj/CUJ-CONTACT.spec.ts'), 'utf8')).toContain('tel:555');
  expect(invoke('run').status).toBe(2);
  expect(invoke('run', '--base-url', 'https://preview.test').stdout).toContain('missing @playwright/test');
});
