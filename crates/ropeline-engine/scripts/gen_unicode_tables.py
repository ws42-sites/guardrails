"""Generate src/unicode_tables.rs from the CPython this port must match.

The engine reproduces Python str behaviour, and CPython 3.12 uses Unicode 15.0.
Rust's standard library tracks a newer Unicode, so every property the Python
code depends on is read from CPython here and compiled in as data.

    python crates/ropeline-engine/scripts/gen_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "src" / "unicode_tables.rs"
SURROGATES = range(0xD800, 0xE000)


def codepoints():
    return (c for c in range(0x110000) if c not in SURROGATES)


def ranges(predicate):
    result, start, previous = [], None, None
    for code in codepoints():
        if predicate(chr(code)):
            if start is None:
                start = code
            previous = code
        elif start is not None:
            result.append((start, previous))
            start = None
    if start is not None:
        result.append((start, previous))
    return result


def emit_ranges(name, doc, table):
    body = ",".join(f"({a:#x},{b:#x})" for a, b in table)
    return f"/// {doc}\npub static {name}: &[(u32, u32)] = &[{body}];\n\n"


def emit_map(name, doc, table):
    def literal(text):
        escape = chr(92) + "u"
        return '"' + "".join(f"{escape}{{{ord(c):x}}}" for c in text) + '"'

    body = ",".join(f"({code:#x},{literal(text)})" for code, text in table)
    return f"/// {doc}\npub static {name}: &[(u32, &str)] = &[{body}];\n\n"


def mapping(function):
    return [
        (code, function(chr(code)))
        for code in codepoints()
        if function(chr(code)) != chr(code)
    ]


def cased(char):
    return char.islower() or char.isupper() or unicodedata.category(char) == "Lt"


def case_ignorable(char):
    # Final sigma is the one place CPython consults the property, so probe it:
    # A<char>SIGMA lowercases to a final sigma when <char> is cased or ignorable.
    final = ("A" + char + "\u03a3").lower()[-1] == "\u03c2"
    return final and not cased(char)


def main():
    out = [
        (
            "// @generated by scripts/gen_unicode_tables.py from CPython "
            f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). "
            "Do not edit.\n\n"
        ),
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n\n',
        emit_ranges("SPACE", "str.isspace()", ranges(str.isspace)),
        emit_ranges(
            "WORD",
            "the regex word class for str patterns: isalnum() or underscore",
            ranges(lambda c: c.isalnum() or c == "_"),
        ),
        emit_ranges(
            "OTHER",
            "unicodedata.category starts with C (Cc, Cf, Cs, Co, Cn)",
            ranges(lambda c: unicodedata.category(c).startswith("C")),
        ),
        emit_ranges(
            "ASSIGNED",
            "characters with a name in this Unicode version",
            ranges(lambda c: unicodedata.category(c) != "Cn"),
        ),
        emit_ranges("CASED", "Cased property", ranges(cased)),
        emit_ranges(
            "CASE_IGNORABLE", "Case_Ignorable property", ranges(case_ignorable)
        ),
        emit_ranges(
            "ID_START", "str.isidentifier() on one character", ranges(str.isidentifier)
        ),
        emit_ranges(
            "ID_CONTINUE",
            "identifier continuation characters",
            ranges(lambda c: ("a" + c).isidentifier()),
        ),
        emit_map(
            "CASEFOLD",
            "str.casefold() where it changes the character",
            mapping(str.casefold),
        ),
        emit_map("LOWER", "str.lower() of one character", mapping(str.lower)),
        emit_map("UPPER", "str.upper() of one character", mapping(str.upper)),
        emit_map("TITLE", "str.title() of one character", mapping(str.title)),
    ]
    TARGET.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
